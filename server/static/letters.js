// 每个字母占多宽（四线格里），按字形算
const WIDTH = {};
for (const [ch, strokes] of Object.entries(LETTERS)) {
  let maxX = 0;
  for (const s of strokes) for (const [x] of s) maxX = Math.max(maxX, x);
  WIDTH[ch] = Math.ceil(maxX + 8);
}
WIDTH[" "] = 18;

// 笔画名字（演示时屏幕上说）
function strokeHint(ch, i, s) {
  const [x0, y0] = s[0], [x1, y1] = s[s.length - 1];
  const where = y0 <= 2 ? "第一线" : Math.abs(y0 - L_MID) < 4 ? "第二线" : Math.abs(y0 - L_BASE) < 4 ? "第三线" : y0 > L_BASE ? "下格" : "中间";
  return `第 ${i + 1} 笔从${where}起笔`;
  void x0; void x1; void y1;
}

